"""
Relevance Ranking Model for AI Brain retrieval candidate re-ranking.
"""

from datetime import datetime, timezone
import json
import math
from types import MappingProxyType
from typing import Any, Dict, List, Optional, Sequence, Tuple

from ai_brain.ml.base import BaseMLModel, ModelMetadata, ModelPrediction, ModelType
from ai_brain.ml.datasets.schemas import DatasetSplit
from ai_brain.ml.exceptions import ModelNotTrainedError
from ai_brain.retrieval.models import RetrievalItem


class RelevanceRankingModel(BaseMLModel):
    """
    ML-enhanced relevance re-ranking model for candidate memories retrieved via Vector/Graph/Hybrid search.
    
    Acts as an optional secondary re-ranker over candidates generated by RetrievalEngine.
    Preserves all existing retrieval filters, safety thresholds, and score breakdowns.
    """

    FEATURE_NAMES = (
        "base_retrieval_score",
        "vector_score",
        "graph_score",
        "importance",
        "confidence",
        "recency_factor",
        "query_term_overlap",
        "is_exact_agent_match",
        "status_penalty",
    )

    def __init__(self, metadata: Optional[ModelMetadata] = None, weights: Optional[Dict[str, float]] = None, bias: float = 0.0) -> None:
        super().__init__(metadata)
        self.weights = weights or {f: 0.0 for f in self.FEATURE_NAMES}
        self.bias = bias

    @property
    def model_type(self) -> ModelType:
        return ModelType.RANKING

    def extract_features(self, item: RetrievalItem, query: str = "", active_agent_id: Optional[str] = None) -> Dict[str, float]:
        """Extract ranking features from a candidate RetrievalItem."""
        base_score = float(getattr(item, "score", 0.0))
        vec_score = float(getattr(item, "vector_score", 0.0) or 0.0)
        graph_score = float(getattr(item, "graph_score", 0.0) or 0.0)
        imp = float(getattr(item, "importance", 0.5) if hasattr(item, "importance") else 0.5)
        conf = float(getattr(item, "confidence", 1.0) if hasattr(item, "confidence") else 1.0)

        # Query term overlap
        q_words = set(query.lower().split())
        c_words = set(str(getattr(item, "content", "")).lower().split())
        overlap = len(q_words.intersection(c_words)) / max(1, len(q_words)) if q_words else 0.0

        # Agent match
        source_agents = getattr(item, "source_agent_ids", ())
        is_agent_match = 1.0 if (active_agent_id and active_agent_id in source_agents) else 0.0

        # Recency
        decay = 1.0
        c_at = getattr(item, "created_at", None)
        if isinstance(c_at, datetime):
            now = datetime.now(timezone.utc)
            if c_at.tzinfo is None:
                c_at = c_at.replace(tzinfo=timezone.utc)
            days = max(0.0, (now - c_at).total_seconds()) / 86400.0
            decay = math.exp(-days / 30.0)

        # Status penalty
        status = str(getattr(item, "status", "ACTIVE")).upper()
        stat_penalty = 0.0
        if status == "DISPUTED" or getattr(item, "is_disputed", False):
            stat_penalty = 0.3
        elif status == "SUPERSEDED":
            stat_penalty = 0.8
        elif status == "ARCHIVED":
            stat_penalty = 0.6

        return {
            "base_retrieval_score": base_score,
            "vector_score": vec_score,
            "graph_score": graph_score,
            "importance": imp,
            "confidence": conf,
            "recency_factor": round(decay, 4),
            "query_term_overlap": round(overlap, 4),
            "is_exact_agent_match": is_agent_match,
            "status_penalty": stat_penalty,
        }

    def predict(self, item: Any, **context: Any) -> ModelPrediction:
        """Predict re-ranked relevance score."""
        if not self.is_trained:
            base_score = float(getattr(item, "score", 0.5))
            return ModelPrediction(
                target_value=round(base_score, 4),
                confidence=0.5,
                feature_contributions=MappingProxyType({}),
                model_version=self.metadata.version if self.metadata else "fallback-untrained",
                fallback_used=True,
                explanation="Model untrained; fell back to existing deterministic score",
            )

        query = str(context.get("query", ""))
        active_agent = context.get("active_agent_id")
        feats = self.extract_features(item, query=query, active_agent_id=active_agent)

        raw_score = self.bias
        contributions = {}
        for f, val in feats.items():
            w = self.weights.get(f, 0.0)
            contrib = w * val
            contributions[f] = round(contrib, 4)
            raw_score += contrib

        # Bounded sigmoid in [0.0, 1.0]
        sig_score = 1.0 / (1.0 + math.exp(-max(-15.0, min(15.0, raw_score))))

        return ModelPrediction(
            target_value=round(sig_score, 4),
            confidence=0.85,
            feature_contributions=MappingProxyType(contributions),
            model_version=self.metadata.version if self.metadata else "v1.0",
            fallback_used=False,
            explanation=f"Re-ranked score={sig_score:.3f} (base_score={feats['base_retrieval_score']:.2f})",
        )

    def rerank(self, items: Sequence[RetrievalItem], query: str = "", active_agent_id: Optional[str] = None) -> List[RetrievalItem]:
        """Re-rank candidate items using ML predictions, preserving tie-breaking by memory_id."""
        if not self.is_trained or not items:
            return list(items)

        scored_pairs = []
        for it in items:
            pred = self.predict(it, query=query, active_agent_id=active_agent_id)
            ml_score = float(pred.target_value)
            scored_pairs.append((ml_score, it, pred))

        # Sort descending by ml_score, tie-break by memory_id
        scored_pairs.sort(key=lambda x: (-x[0], x[1].memory_id))

        reranked = []
        for ml_score, it, pred in scored_pairs:
            # Create updated retrieval item with ml_score noted in metadata without mutating original
            meta = dict(it.metadata)
            meta["ml_rank_score"] = ml_score
            meta["ml_explanation"] = pred.explanation

            new_item = RetrievalItem(
                memory_id=it.memory_id,
                root_memory_id=it.root_memory_id,
                version=it.version,
                project_id=it.project_id,
                content=it.content,
                memory_type=it.memory_type,
                status=it.status,
                score=round(ml_score, 4),
                score_breakdown=it.score_breakdown,
                vector_score=it.vector_score,
                graph_score=it.graph_score,
                graph_metadata=it.graph_metadata,
                sources=it.sources,
                source_event_ids=it.source_event_ids,
                source_agent_ids=it.source_agent_ids,
                is_disputed=it.is_disputed,
                created_at=it.created_at,
                metadata=MappingProxyType(meta),
            )
            reranked.append(new_item)

        return reranked

    def train(self, dataset: DatasetSplit, learning_rate: float = 0.05, epochs: int = 100, l2_reg: float = 0.01) -> Dict[str, float]:
        train_examples = dataset.train_examples
        if not train_examples:
            raise ModelNotTrainedError("Cannot train with empty dataset split")

        weights = {f: 0.0 for f in self.FEATURE_NAMES}
        weights["base_retrieval_score"] = 2.0
        weights["vector_score"] = 1.0
        weights["graph_score"] = 0.8
        weights["query_term_overlap"] = 1.2
        weights["importance"] = 0.5
        weights["status_penalty"] = -1.5
        bias = 0.0

        n = len(train_examples)
        for _ in range(epochs):
            grad_w = {f: 0.0 for f in self.FEATURE_NAMES}
            grad_b = 0.0

            for ex in train_examples:
                y = float(ex.label)
                logit = bias + sum(weights[f] * ex.features.get(f, 0.0) for f in self.FEATURE_NAMES)
                p = 1.0 / (1.0 + math.exp(-max(-15.0, min(15.0, logit))))
                err = p - y

                grad_b += err
                for f in self.FEATURE_NAMES:
                    grad_w[f] += err * ex.features.get(f, 0.0)

            bias -= learning_rate * (grad_b / n)
            for f in self.FEATURE_NAMES:
                weights[f] -= learning_rate * ((grad_w[f] / n) + (l2_reg * weights[f]))

        self.weights = weights
        self.bias = bias
        self._is_trained = True

        from ai_brain.ml.training.evaluator import ModelEvaluator

        val_errors = []
        val_ranked_lists: List[List[float]] = []
        curr_query_rels: List[Tuple[float, float]] = [] # (predicted_score, ground_truth)

        for ex in dataset.validation_examples:
            y = float(ex.label)
            logit = bias + sum(weights[f] * ex.features.get(f, 0.0) for f in self.FEATURE_NAMES)
            p = 1.0 / (1.0 + math.exp(-max(-15.0, min(15.0, logit))))
            val_errors.append(abs(p - y))
            curr_query_rels.append((p, y))

        # Sort by predicted score descending to evaluate ranking quality
        curr_query_rels.sort(key=lambda x: -x[0])
        ranked_rels = [gt for _, gt in curr_query_rels]
        if ranked_rels:
            val_ranked_lists.append(ranked_rels)

        ranking_metrics = ModelEvaluator.evaluate_ranking(val_ranked_lists)
        mae = sum(val_errors) / len(val_errors) if val_errors else 0.0

        metrics = {
            "mae": round(mae, 4),
            "ndcg_at_5": round(ranking_metrics.ndcg_at_5, 4),
            "ndcg_at_10": round(ranking_metrics.ndcg_at_10, 4),
            "mrr": round(ranking_metrics.mrr, 4),
        }

        self.metadata = ModelMetadata(
            model_name="RelevanceRankingModel",
            model_type=ModelType.RANKING,
            version="1.0.0",
            created_at=datetime.now(timezone.utc),
            feature_names=self.FEATURE_NAMES,
            parameters=MappingProxyType({"weights": self.weights, "bias": self.bias}),
            metrics=MappingProxyType(metrics),
            training_data_provenance=dataset.name,
            description="Calibrated multi-stream relevance ranking and scoring model",
        )
        return metrics

    def save(self, filepath: str) -> None:
        data = {
            "metadata": self.metadata.to_dict() if self.metadata else None,
            "weights": self.weights,
            "bias": self.bias,
        }
        with open(filepath, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2)

    @classmethod
    def load(cls, filepath: str) -> "RelevanceRankingModel":
        with open(filepath, "r", encoding="utf-8") as f:
            data = json.load(f)
        meta = ModelMetadata.from_dict(data["metadata"]) if data.get("metadata") else None
        return cls(metadata=meta, weights=data.get("weights"), bias=float(data.get("bias", 0.0)))
